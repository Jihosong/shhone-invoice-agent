import pytest

from feedback import category_of, normalize_spec, reg_no_map


@pytest.mark.parametrize("raw, expected", [
    ("Ø38 0~ 0.04", "Ø38 +0~+0.04"),
    ("Ø425 0.03", "Ø425 +0.03"),
    ("Ø117.52~117.54", "Ø117.52~117.54"),
    ("-0.01~-0.03", "-0.01~-0.03"),
    ("Ø14 ±0.02/310", "Ø14 ±0.02/310"),
    ("Ø120+0.0~+0.03 / 506", "Ø120 +0.0~+0.03 / 506"),
    # 실제 데이터에서 본 추가 형태
    ("Ø250 0.0~ 0.05 / 520", "Ø250 +0.0~+0.05 / 520"),
    ("Ø76.048 -0.025~ 0.025", "Ø76.048 -0.025~+0.025"),
    ("Ø13 0.15 / 145", "Ø13 +0.15 / 145"),
    ("Ø100/0~+0.054", "Ø100/+0~+0.054"),
    ("Ø450-0.2~-0.15 / 595", "Ø450 -0.2~-0.15 / 595"),
    ("Ø40/775", "Ø40/775"),
    ("Ø55 / 610L", "Ø55 / 610L"),
    ("Ra 0.8", "Ra 0.8"),
    (None, None),
])
def test_normalize_spec(raw, expected):
    assert normalize_spec(raw) == expected


def test_reg_no_map_same_name():
    m = reg_no_map([("가사", "111-11-11111"), ("나사", "333-33-33333"), ("나사", "222-22-22222")])
    assert m == {"가사": "111-11-11111", "나사": "동명:222-22-22222/333-33-33333"}


def test_category():
    assert category_of("호닝파이프") == "기성품"
    assert category_of("소관파이프") == "기성품"
    assert category_of("시린더호닝") == "임가공"
